export const postalKey = (fmt: AddressFormat) => `postal_${fmt.kind}` as AddressKey;
export const regionKey = (fmt: AddressFormat) => `region_${fmt.kind}` as AddressKey;
/** Só existe para formatos com hasParish (BR, PT). */
export const parishKey = (fmt: AddressFormat) => (fmt.kind === 'br_cep' ? 'parish_br_cep' : 'parish_pt_cp') as AddressKey;
