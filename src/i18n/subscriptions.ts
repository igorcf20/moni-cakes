/** "Todo mês", "A cada 2 semanas"... */
export function everyText(t: (k: SubscriptionsKey, v?: Record<string, string | number>) => string, unit: string, count: number): string {
  if (unit === 'week') return count === 1 ? t('every_week_one') : t('every_week', { n: count });
  return count === 1 ? t('every_month_one') : t('every_month', { n: count });
}
