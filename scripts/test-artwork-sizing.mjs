import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import { File } from "node:buffer";
import { PDFDocument, degrees } from "pdf-lib";

const code = ts.transpileModule(readFileSync(new URL("../src/lib/artworkSizing.ts", import.meta.url), "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
}).outputText.replace('import("pdf-lib")', `import(${JSON.stringify(pathToFileURL(createRequire(import.meta.url).resolve("pdf-lib")).href)})`);
const { fitArtwork, imageDensity, artworkQuality, sizingSignature, artworkReviewComplete, inspectArtwork, verifyArtworkOriginal } = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);
const fit = fitArtwork(32, 44, 30, 40);
assert.equal(fit.heightCm, 40);
assert.ok(Math.abs(fit.widthCm - 29.09090909090909) < 1e-10);
assert.equal(fit.widthCm / fit.heightCm, 32 / 44);
assert.equal(fit.reduced, true);
assert.deepEqual(fitArtwork(10, 12, 30, 40), { widthCm: 10, heightCm: 12, reduced: false });
assert.equal(fitArtwork(100, 1, 30, 40).heightCm, 0.3);
for (const n of [0, -1, NaN, Infinity]) assert.throws(() => fitArtwork(n, 44, 30, 40));
assert.equal(imageDensity(new Uint8Array(0)), null);
const png = new Uint8Array(29), view = new DataView(png.buffer);
view.setUint32(0, 0x89504e47); view.setUint32(4, 0x0d0a1a0a);
view.setUint32(8, 9); view.setUint32(12, 0x70485973);
view.setUint32(16, 11811); view.setUint32(20, 11811); png[24] = 1;
assert.ok(Math.abs(imageDensity(png).x - 300) < 0.01);
png[24] = 0; assert.equal(imageDensity(png), null);
const jpeg = new Uint8Array([255,216,255,224,0,16,74,70,73,70,0,1,1,1,1,44,1,44,0,0]);
assert.deepEqual(imageDensity(jpeg), { x: 300, y: 300 });
const meta = { originalFileName: "arte.png", originalBytes: 10000, sha256: "original-hash", widthPx: 600, heightPx: 825, sourceWidthCm: 32, sourceHeightCm: 44, dimensionSource: "embedded" };
assert.equal(artworkQuality(meta, fit.widthCm, fit.heightCm).status, "low");
assert.equal(artworkQuality({ ...meta, widthPx: undefined }, 30, 40).status, "unverified");
const value = { artwork: meta, ...fit };
assert.equal(artworkReviewComplete(value), false);
const signature = sizingSignature(meta, fit.widthCm, fit.heightCm);
assert.equal(artworkReviewComplete({ ...value, acceptedSizing: signature }), false);
assert.equal(artworkReviewComplete({ ...value, acceptedSizing: signature, acceptedQuality: signature }), true);
assert.equal(artworkReviewComplete({ ...value, widthCm: 20, acceptedSizing: signature, acceptedQuality: signature }), false);
assert.equal(artworkReviewComplete({ ...value, artwork: { ...meta, sha256: "replaced" }, acceptedSizing: signature, acceptedQuality: signature }), false);
assert.equal(artworkReviewComplete({ ...value, artwork: { ...meta, sourceWidthCm: undefined }, acceptedSizing: signature, acceptedQuality: signature }), false);
const original = new File([jpeg], "original.jpg", { type: "image/jpeg" });
const inspected = await inspectArtwork(original, 600, 825);
assert.equal(inspected.originalBytes, jpeg.length);
assert.equal(inspected.originalFileName, "original.jpg");
assert.equal(inspected.dimensionSource, "embedded");
assert.ok(Math.abs(inspected.sourceWidthCm - 5.08) < 1e-10);
const dataUrl = `data:image/jpeg;base64,${Buffer.from(jpeg).toString("base64")}`;
await verifyArtworkOriginal(dataUrl, inspected);
await assert.rejects(() => verifyArtworkOriginal(dataUrl, { ...inspected, sha256: "corrupt" }));
await assert.rejects(() => verifyArtworkOriginal(dataUrl, { ...inspected, originalBytes: 999 }));
const unknown = await inspectArtwork(new File([png], "without-density.png", { type: "image/png" }), 600, 825);
assert.equal(unknown.dimensionSource, "unknown");
assert.equal(unknown.sourceWidthCm, undefined);
const pdf = await PDFDocument.create();
const page = pdf.addPage([32 * 72 / 2.54, 44 * 72 / 2.54]);
let pdfMeta = await inspectArtwork(new File([await pdf.save()], "art.pdf", { type: "application/pdf" }));
assert.ok(Math.abs(pdfMeta.sourceWidthCm - 32) < 1e-10);
assert.ok(Math.abs(pdfMeta.sourceHeightCm - 44) < 1e-10);
page.setRotation(degrees(90));
pdfMeta = await inspectArtwork(new File([await pdf.save()], "rotated.pdf", { type: "application/pdf" }));
assert.ok(Math.abs(pdfMeta.sourceWidthCm - 44) < 1e-10);
pdf.addPage();
await assert.rejects(async () => inspectArtwork(new File([await pdf.save()], "two-pages.pdf", { type: "application/pdf" })));
console.log("Artwork sizing: proportional fit, density, quality and consent regression checks passed.");
